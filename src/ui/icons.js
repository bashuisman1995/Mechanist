export function icon(name, o) {
  o = o || {};
  const body = P[name];
  if (!body) return "";
  const s = o.size || 20;
  return '<svg class="ic' + (o.cls ? " " + o.cls : "") + '" width="' + s + '" height="' + s + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" ' +
    'stroke-width="' + (o.sw || 1.75) + '" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + body + "</svg>";
}
export const hasIcon = name => !!P[name];

// <i data-ic="naam" data-ic-size="16"> -> inline svg (idempotent)
export function hydrateIcons(root) {
  (root || document).querySelectorAll("[data-ic]").forEach(el => {
    const n = el.getAttribute("data-ic");
    if (el.dataset.icDone === n) return;
    el.innerHTML = icon(n, { size: +el.getAttribute("data-ic-size") || 0 || 20 });
    el.dataset.icDone = n;
  });
}
